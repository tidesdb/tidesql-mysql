static bool tidesdb_hton_flush_logs(TDB_HTON_FLUSH_LOGS_ARGS);
static int tidesdb_hton_panic(handlerton *, enum ha_panic_function flag);
static void tidesdb_hton_pre_shutdown(TDB_HTON_PRE_SHUTDOWN_ARGS);

static int tidesdb_init_func(void *p)
{
    DBUG_ENTER("tidesdb_init_func");

    /* First, and on every path: the linked library registers a thread-exit callback that lives in
       this module, and the server unloads the module before the process exits.  See
       TDB_PIN_PLUGIN_MODULE for what that costs and why the plugin is what has to deal with it.
       Nothing below depends on it, so it happens here rather than somewhere an early return could
       skip. */
    TDB_PIN_PLUGIN_MODULE();

    tidesdb_hton = (handlerton *)p;
    tidesdb_hton->create = tidesdb_create_handler;
    /* Where the server hands the engine its foreign-key definitions, the engine advertises that it
       enforces them; where it does not, the flag is withheld.  The compat layer records why the two
       cannot simply be set the same way. */
    tidesdb_hton->flags = TDB_HTON_FLAGS;

    /* DDL atomicity, and the foreign-key support the server couples to it. */
    tdb_ddl_register_hooks(tidesdb_hton);
    tidesdb_hton->TDB_HTON_FILE_EXTENSIONS = ha_tidesdb_exts;
    TDB_REGISTER_TABLE_OPTIONS(tidesdb_hton);
    TDB_HTON_SET_DROP_TABLE(tidesdb_hton, tidesdb_hton_drop_table);
    tidesdb_hton->drop_database = tidesdb_hton_drop_database;

    /* transaction, savepoint, and connection-close callbacks plus the savepoint storage size */
    tidesdb_txn_register(tidesdb_hton);
    tidesdb_hton->show_status = tidesdb_show_status;

    /* Durability / lifecycle / cancellation hooks. */
    tidesdb_hton->flush_logs = tidesdb_hton_flush_logs;
    tidesdb_hton->panic = tidesdb_hton_panic;
    tidesdb_hton->TDB_HTON_PRE_SHUTDOWN = tidesdb_hton_pre_shutdown;

    /* Arm the full-text locks, seed the default stop words, and build the blend map. */
    fts_init();

    /* We use tidesdb_data_home_dir if set, otherwise compute
       a sibling directory of the server data directory. */
    if (srv_data_home_dir && srv_data_home_dir[0])
    {
        tdb_path = srv_data_home_dir;
        while (!tdb_path.empty() && tdb_path.back() == '/') tdb_path.pop_back();
    }
    else
    {
        std::string data_home(mysql_real_data_home);
        while (!data_home.empty() && data_home.back() == '/') data_home.pop_back();
        size_t slash_pos = data_home.rfind('/');
        if (slash_pos != std::string::npos)
            tdb_path = data_home.substr(0, slash_pos + 1) + "tidesdb_data";
        else
            tdb_path = "tidesdb_data";
    }

    static const int log_level_map[] = {TDB_LOG_TRACE, TDB_LOG_INFO, TDB_LOG_WARN, TDB_LOG_ERROR,
                                        TDB_LOG_NONE};

    tidesdb_config_t cfg = tidesdb_default_config();
    cfg.db_path = const_cast<char *>(tdb_path.c_str());
    cfg.num_flush_threads = (int)srv_flush_threads;
    cfg.num_compaction_threads = (int)srv_compaction_threads;
    cfg.log_level = (tidesdb_log_level_t)log_level_map[srv_log_level];
    cfg.block_cache_size = (size_t)srv_block_cache_size;
    cfg.max_open_sstables = (int)srv_max_open_sstables;
    cfg.log_to_file = srv_log_to_file ? 1 : 0;
    cfg.log_truncation_at = (size_t)srv_log_truncation_at;
    cfg.memtable_write_buffer_size = (size_t)srv_memtable_write_buffer_size;
    cfg.memtable_sync_mode = tdb_sync_mode_map[srv_memtable_sync_mode];
    cfg.memtable_sync_interval_us = (uint64_t)srv_memtable_sync_interval;
    cfg.memtable_skip_list_max_level = (int)srv_memtable_skip_list_max_level;
    cfg.memtable_skip_list_probability = (float)srv_memtable_skip_list_probability;
    /* cfg already carries the library defaults from tidesdb_default_config, so only
       override the value log segment size and the l0 stall threshold when the operator
       set them, keeping zero as the meaning follow the library. */
    if (srv_vlog_segment_size) cfg.vlog_segment_size = (size_t)srv_vlog_segment_size;
    if (srv_value_separation_threshold)
        cfg.value_separation_threshold = (size_t)srv_value_separation_threshold;
    if (srv_memtable_l0_queue_stall_threshold)
        cfg.memtable_l0_queue_stall_threshold = (int)srv_memtable_l0_queue_stall_threshold;
    if (srv_memtable_idle_flush_seconds >= 0)
        cfg.memtable_idle_flush_seconds = (int)srv_memtable_idle_flush_seconds;
    if (srv_txn_timeout_seconds >= 0) cfg.txn_timeout_seconds = (int64_t)srv_txn_timeout_seconds;

    int rc = tidesdb_open(&cfg, &tdb_global);
    if (rc != TDB_SUCCESS)
    {
        sql_print_error("[TIDESDB] Failed to open TidesDB at %s (err=%d)", tdb_path.c_str(), rc);
        DBUG_RETURN(1);
    }

    sql_print_information("[TIDESDB] TidesDB opened at %s", tdb_path.c_str());

    /* Key custody comes up after the database, because the backend that assembles it holds the
       wrapped table keys in a reserved column family and has to open or create that family here.
       A server with no key custody configured is not a failure: it only prevents a table from
       being created with encryption, which create() reports at that point. */
    if (!tdb_crypto_init())
    {
        sql_print_error("[TIDESDB] data-at-rest key custody failed to initialise");
        tidesdb_close(tdb_global);
        tdb_global = NULL;
        DBUG_RETURN(1);
    }

    /* Backup, checkpoint and key rotation.  A failure to register is reported and left at that:
       the engine still stores and serves data without them. */
    tdb_udf_register_all();

    DBUG_RETURN(0);
}

/*
  Handlerton-level FLUSH LOGS callback.  Called on FLUSH LOGS and by
  an external backup tool before copying files so the on-disk WAL is a consistent
  snapshot.  The write-ahead log is db-level in TidesDB 10, so a single
  tidesdb_sync_wal covers every column family.  Returns false on success
  (handlerton convention).
*/
static bool tidesdb_hton_flush_logs(TDB_HTON_FLUSH_LOGS_ARGS)
{
    if (!tdb_global) return false;

    /* the write-ahead log is db-level in TidesDB 10, so one sync covers every cf. */
    int rc = tidesdb_sync_wal(tdb_global);
    if (rc != TDB_SUCCESS)
    {
        sql_print_warning("[TIDESDB] flush_logs: tidesdb_sync_wal failed (rc=%d)", rc);
        return true; /* error */
    }
    return false;
}

/*
  Handlerton-level panic callback.  the server calls this on signal-driven or
  abnormal shutdown paths where tidesdb_deinit_func may not run.  We only
  react to HA_PANIC_CLOSE -- the other flags are legacy ISAM-era.
*/
static int tidesdb_hton_panic(handlerton *, enum ha_panic_function flag)
{
    if (flag != HA_PANIC_CLOSE) return 0;

    if (tdb_global)
    {
        tidesdb_close(tdb_global);
        tdb_global = NULL;
    }
    return 0;
}

/*
  Handlerton-level pre_shutdown callback.  Runs before the deinit path so
  background threads that still need a fully-functional server (compaction,
  flush) get a clean signal to drain.  We flush the WAL synchronously
  and let tidesdb_close() in deinit finish the teardown.
*/
static void tidesdb_hton_pre_shutdown(TDB_HTON_PRE_SHUTDOWN_ARGS)
{
    if (!tdb_global) return;

    /* Sync the WAL so durability is preserved if deinit is racing
       a forced exit.  The call is cheap when there's nothing to sync. */
    (void)tidesdb_hton_flush_logs(tidesdb_hton, false);
}

static int tidesdb_deinit_func(void *p [[maybe_unused]])
{
    DBUG_ENTER("tidesdb_deinit_func");

    if (tdb_global)
    {
        /* tidesdb_close performs the orderly teardown, flushing pending commits
           and quiescing the background workers. */
        tidesdb_close(tdb_global);
        tdb_global = NULL;
    }

    tdb_udf_unregister_all();
    tdb_crypto_deinit();
    fts_deinit();

    sql_print_information("[TIDESDB] TidesDB closed");
    DBUG_RETURN(0);
}

