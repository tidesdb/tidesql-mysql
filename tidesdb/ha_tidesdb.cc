/*
  Map TidesDB library error codes to server handler error codes.
  A commit-time write conflict maps to HA_ERR_LOCK_DEADLOCK so that the server's
  deadlock-retry logic kicks in and applications retry automatically instead of
  receiving the opaque HA_ERR_GENERIC / ER_GET_ERRNO 1030.  Transient
  contention and memtable backpressure map instead to HA_ERR_LOCK_WAIT_TIMEOUT,
  which rolls back only the current statement rather than the whole transaction.
*/
int tdb_rc_to_ha(int rc, const char *ctx)
{
    switch (rc)
    {
        case TDB_SUCCESS:
            return 0;

        /* Transient concurrency errors -- mapped to deadlock so the server
           rolls back the transaction and the application can retry. */
        case TDB_ERR_CONFLICT:
            return HA_ERR_LOCK_DEADLOCK;

        /* The library aborted this transaction from outside, so from that point every operation on
           it, its commit included, returns TDB_ERR_TXN_ABORTED.  Surface it as a deadlock so the
           losing side rolls back and retries rather than seeing an opaque failure. */
        case TDB_ERR_TXN_ABORTED:
            return HA_ERR_LOCK_DEADLOCK;

        /* The transaction outlived its timeout and the library aborted it; a lock-wait timeout is
           the closest server error and drives the same statement-level retry. */
        case TDB_ERR_TXN_EXPIRED:
            return HA_ERR_LOCK_WAIT_TIMEOUT;

        /* Lock wait timeout -- rolls back the current statement only
           (not the whole transaction), less disruptive than full deadlock. */
        case TDB_ERR_LOCKED:
            return HA_ERR_LOCK_WAIT_TIMEOUT;

        /* Soft memtable-capacity backpressure from the library (memtable,
           flush queue, or L0 backlog at its cap).  The library absorbs this
           through its own L0 admission policy and only returns it once its
           internal no-progress budget is spent, so by the time it reaches the
           plugin it is a transient signal to retry.  Map it to lock-wait-timeout,
           which is the accurate name here (not deadlock; nothing is locked). */
        case TDB_ERR_MEMORY_LIMIT:
            return HA_ERR_LOCK_WAIT_TIMEOUT;

        /* Hard out-of-memory.  Distinct from TDB_ERR_MEMORY_LIMIT above
           (a soft back-pressure signal); TDB_ERR_MEMORY means the
           allocator itself failed. */
        case TDB_ERR_MEMORY:
            sql_print_error("[TIDESDB] %s: TDB_ERR_MEMORY", ctx);
            return HA_ERR_OUT_OF_MEM;

        case TDB_ERR_NOT_FOUND:
            return HA_ERR_KEY_NOT_FOUND;

        case TDB_ERR_EXISTS:
            return HA_ERR_FOUND_DUPP_KEY;

        case TDB_ERR_READONLY:
            return HA_ERR_READ_ONLY_TRANSACTION;

        /* I/O and corruption errors -- table needs repair/recovery.
           matches InnoDB's mapping of DB_CORRUPTION to HA_ERR_CRASHED. */
        case TDB_ERR_IO:
            sql_print_error("[TIDESDB] %s: I/O error (TDB_ERR_IO)", ctx);
            return HA_ERR_CRASHED;

        case TDB_ERR_CORRUPTION:
            sql_print_error("[TIDESDB] %s: data corruption detected (TDB_ERR_CORRUPTION)", ctx);
            return HA_ERR_CRASHED;

        /* Row too large for the configured block/value size. */
        case TDB_ERR_TOO_LARGE:
            return HA_ERR_TO_BIG_ROW;

        /* Database handle invalid (closed or never opened). */
        case TDB_ERR_INVALID_DB:
            sql_print_error("[TIDESDB] %s: invalid database handle (TDB_ERR_INVALID_DB)", ctx);
            return HA_ERR_INTERNAL_ERROR;

        /* Invalid arguments -- programming error in the plugin. */
        case TDB_ERR_INVALID_ARGS:
            sql_print_error("[TIDESDB] %s: invalid arguments (TDB_ERR_INVALID_ARGS)", ctx);
            return HA_ERR_INTERNAL_ERROR;

        /* A commit returns TDB_ERR_UNKNOWN when the shared memtable's active
           try_ref retry budget is exhausted under heavy rotation contention --
           same family as TDB_ERR_CONFLICT from the caller's perspective.
           Map to HA_ERR_LOCK_DEADLOCK so the server triggers its deadlock
           retry path instead of surfacing an opaque ER_GET_ERRNO 1030. */
        case TDB_ERR_UNKNOWN:
            return HA_ERR_LOCK_DEADLOCK;

        default:
            sql_print_warning("[TIDESDB] %s: unexpected TidesDB error rc=%d", ctx, rc);
            return HA_ERR_GENERIC;
    }
}

